#!/usr/bin/env python3
"""Mix voice-over + music + UI clicks onto the rendered video.

usage: python3 engine/mix.py episodes/<name> [--voice-dir DIR] [--music FILE] [--out FILE]
Defaults: voice from .cache/<name>/voice, music generated by engine/music.py,
output renders/<name>/<name>-<YYYYMMDD-HHMM>.mp4 (renders/ is git-ignored).
--voice-dir lets you drop in other voice files (e.g. ElevenLabs exports named v1.wav/v1.mp3 ...).
"""
import json, os, sys, subprocess, argparse, datetime

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ap = argparse.ArgumentParser()
ap.add_argument('episode')
ap.add_argument('--voice-dir')
ap.add_argument('--music')
ap.add_argument('--out')
a = ap.parse_args()

ep_dir = os.path.abspath(a.episode)
name = os.path.basename(ep_dir)
ep = json.load(open(os.path.join(ep_dir, 'episode.json')))
D = ep['duration']
cache = os.path.join(ROOT, '.cache', name)
video = os.path.join(cache, 'video', 'video.mp4')
voice_dir = a.voice_dir or os.path.join(cache, 'voice')
music = a.music or os.path.join(cache, 'music.wav')
if not a.music:
    subprocess.run([sys.executable, os.path.join(ROOT, 'engine', 'music.py'), str(D), music], check=True)
stamp = datetime.datetime.now().strftime('%Y%m%d-%H%M')
out = a.out or os.path.join(ROOT, 'renders', name, f'{name}-{stamp}.mp4')
os.makedirs(os.path.dirname(out), exist_ok=True)

def voice_file(i):
    for ext in ('wav', 'mp3', 'm4a'):
        p = os.path.join(voice_dir, f'{i}.{ext}')
        if os.path.exists(p):
            return p
    sys.exit(f'missing voice file for {i} in {voice_dir}')

inputs, filt, labels = [], [], []
for k, line in enumerate(ep['voiceover']):
    inputs += ['-i', voice_file(line['id'])]
    ms = int(line['at'] * 1000)
    filt.append(f'[{k}]aresample=48000,pan=mono|c0=c0,adelay={ms}[v{k}]')
    labels.append(f'[v{k}]')
nv = len(labels)
m = ep.get('music', {})
duck = m.get('duck', {})
inputs += ['-i', music]
filt.append(f"{''.join(labels)}amix=inputs={nv}:normalize=0,pan=stereo|c0=c0|c1=c0,volume=1.7,asplit=2[vo][vk]")
filt.append(f"[{nv}]aresample=48000,pan=stereo|c0=c0|c1=c0,volume={m.get('volume', 1.25)}[mus]")
filt.append(f"[mus][vk]sidechaincompress=threshold={duck.get('threshold', 0.03)}:ratio={duck.get('ratio', 4)}:"
            f"attack={duck.get('attack', 60)}:release={duck.get('release', 600)}:makeup=1[musd]")
mixl = ['[vo]', '[musd]']
clicks = ep.get('sfx', {}).get('click', [])
if clicks:
    inputs += ['-f', 'lavfi', '-i', 'sine=f=1200:d=0.04']
    ci = nv + 1
    filt.append(f'[{ci}]afade=t=in:d=0.004,afade=t=out:st=0.004:d=0.036,volume=0.18,aresample=48000,'
                f'pan=stereo|c0=c0|c1=c0,asplit={len(clicks)}' + ''.join(f'[c{j}]' for j in range(len(clicks))))
    for j, t in enumerate(clicks):
        ms = int(t * 1000)
        filt.append(f'[c{j}]adelay={ms}|{ms}[cd{j}]')
        mixl.append(f'[cd{j}]')
filt.append(f"{''.join(mixl)}amix=inputs={len(mixl)}:normalize=0,alimiter=limit=0.9,apad,atrim=0:{D}[a]")
mix_wav = os.path.join(cache, 'mix.wav')
subprocess.run(['ffmpeg', '-y', '-loglevel', 'error', *inputs, '-filter_complex', ';'.join(filt),
                '-map', '[a]', '-c:a', 'pcm_s16le', mix_wav], check=True)
subprocess.run(['ffmpeg', '-y', '-loglevel', 'error', '-i', video, '-i', mix_wav, '-map', '0:v', '-map', '1:a',
                '-c:v', 'copy', '-c:a', 'aac', '-b:a', '192k', '-shortest', out], check=True)
print(f'final → {out}')
